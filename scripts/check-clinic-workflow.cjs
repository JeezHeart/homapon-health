 for(const [id,value] of Object.entries({'cf-first':'Workflow','cf-last':'Fictional','cf-dob':'2026-01-01','cf-guardian':'Fictional Guardian','cf-mobile':'09170000000','cf-purok':'Purok 1'}))await page.locator('#'+id).fill(value);
